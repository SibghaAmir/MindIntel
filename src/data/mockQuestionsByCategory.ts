export function getQuestionBank(category: CaseCategoryId): string[] {
  return QUESTION_BANKS[category] ?? QUESTION_BANKS.anything;
}

export function getQuestionAt(category: CaseCategoryId, index: number): string {
  const bank = getQuestionBank(category);
  if (index < bank.length) return bank[index];
  // Fall back to the "anything" bank once a category's list is exhausted.
  const fallback = QUESTION_BANKS.anything;
  return fallback[index % fallback.length];
}
